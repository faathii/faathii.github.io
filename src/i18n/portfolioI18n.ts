export function getLocalizedProject(project: Project, lang: Lang): Project {
  if (lang === 'es') return project;
  const over = PROJECT_EN_OVERRIDES[project.id];
  if (!over) return project;
  return { ...project, ...over };
}

export function getLocalizedSkillCategories(categories: SkillCategory[], lang: Lang): SkillCategory[] {
  if (lang === 'es') return categories;
  return categories.map((cat, idx) => {
    const over = SKILL_EN_OVERRIDES[idx];
    if (!over) return cat;
    return {
      ...cat,
      title: over.title,
      description: over.description,
      skills: cat.skills.map((s, sIdx) => ({
        ...s,
        name: over.skills[sIdx] ?? s.name,
      })),
    };
  });
}
